# Source: tools/cpsf_v21_segment_units/model.py

def add(x, i, n):
    return x.new_zeros((n, *x.shape[1:])).index_add(0, i, x)

def mlp(a, b):
    return nn.Sequential(nn.Linear(a, b), nn.GELU(), nn.Linear(b, b))

def rotary(x, xyz):
    (b, h, l, d) = x.shape
    assert d % 6 == 0
    v = x.reshape(b, h, l, 3, d // 6, 2)
    freq = 10000.0 ** (-torch.arange(d // 6, device=x.device, dtype=x.dtype) / (d // 6))
    phase = xyz[:, None, :, :, None] * freq
    (co, si) = (phase.cos(), phase.sin())
    (a, c) = (v[..., 0], v[..., 1])
    return torch.stack((a * co - c * si, a * si + c * co), -1).reshape(b, h, l, d)

