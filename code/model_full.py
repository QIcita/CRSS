class DirectionalModel(DeterministicModel):

    def __init__(self, task, arm, descriptor='voxel'):
        assert descriptor in ('voxel', 'directional_xyz', 'directional')
        super().__init__(task, arm, 'voxel')
        self.directional_descriptor = descriptor

    def stems(self, g):
        if self.arm == 'skeleton' or self.directional_descriptor == 'voxel':
            return super().stems(g)
        pf = g['pf_directional']
        if self.directional_descriptor == 'directional_xyz':
            pf = torch.cat((pf[:, :3], g['pf'][:, 3:]), 1)
        return super().stems(dict(g, pf=pf))

TASKS = ('h01_local', 'h01_global', 'flywire_coarse', 'ted', 'tlp')

def build_model(task):
    """Build the exact selected full model; preprocessing remains task-specific."""
    if task in TASKS[:3]:
        return FixedCoreModel(task, 'full')
    if task == 'ted':
        return NreddModel('ted', 'full')
    if task == 'tlp':
        return DirectionalModel('tlp', 'full', 'directional_xyz')
    raise ValueError(f'Unknown task: {task}')

def full_state(task, saved, identity=None):
    """Remove only the documented unused gate tensors in historical H01 controls."""
    state = saved['model'] if 'model' in saved else saved
    dormant = {'gate_alpha', 'region_gate.weight', 'region_gate.bias'}
    present = dormant.intersection(state)
    if present:
        identity = saved.get('identity', identity)
        assert task in ('h01_local', 'h01_global') and present == dormant
        assert identity is not None and identity['arm'] == 'fixed_residual'
        assert all(torch.count_nonzero(state[k]) == 0 for k in dormant)
        state = {k: v for k, v in state.items() if k not in dormant}
    return state

def load_model(task, checkpoint, device='cpu'):
    """Load a bundled, hash-verified state dictionary strictly, including heads."""
    model = build_model(task)
    import json
    from pathlib import Path
    saved = torch.load(checkpoint, map_location='cpu', weights_only=True)
    sidecar = Path(checkpoint).with_name('identity.json')
    identity = json.loads(sidecar.read_text()) if sidecar.exists() else None
    state = full_state(task, saved, identity)
    model.load_state_dict(state, strict=True)
    return model.to(device).eval()
